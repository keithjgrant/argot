import Color from 'colorjs.io';
import { checkName, normalizeOptions } from './validation.ts';
import { generatePalette } from './generatePalette.ts';
import type {
  NormalizedPaletteOptions,
  OklchColor,
  Palette,
  PaletteDefinition,
} from './types.ts';

/**
 * Render a model returned by generatePalette without mutating its raw steps.
 * Gamut mapping happens here, independently of CSS output format.
 */
function renderPaletteCss(palette: Palette): string {
  const options = normalizeOptions(palette.options);
  const blocks = palette.colors.map(({ name, baseStep, steps }) => {
    checkName(name, 'palette color name');
    const lines = steps.map(({ step, l, c, h }) => {
      if (!Number.isInteger(step) || step < 1 || step > 16) {
        throw new Error('palette step: expected an integer from 1 to 16');
      }
      return `  --${name}-${step}: ${formatColor({ l, c, h }, options)};`;
    });
    if (!Number.isInteger(baseStep) || baseStep < 1 || baseStep > 16) {
      throw new Error('palette baseStep: expected an integer from 1 to 16');
    }
    lines.push(`  --${name}: var(--${name}-${baseStep});`);
    return lines.join('\n');
  });
  return [
    '/* Generated by Argot. */',
    ':root {',
    blocks.join('\n\n'),
    '}',
    '',
  ].join('\n');
}

function formatColor(
  { l, c, h }: OklchColor,
  { format, gamut }: NormalizedPaletteOptions,
): string {
  if (![l, c, h].every(Number.isFinite)) {
    throw new Error('palette coordinates: expected finite OKLCH values');
  }
  const color = new Color('oklch', [l, c, h]).toGamut({
    space: gamut,
    method: 'css',
  });
  if (format === 'hex') {
    return color.to('srgb').toString({ format: 'hex', collapse: false });
  }
  return color.to('oklch').toString({ precision: 6 });
}

function generatePaletteCss(definition: PaletteDefinition): string {
  return renderPaletteCss(generatePalette(definition));
}

export { renderPaletteCss, generatePaletteCss };
